import { expect, test } from '@playwright/test'

test('generates exact bank quotas, replaces without duplicates, and keeps changes after reload', async ({ page }) => {
  await page.goto('/about')
  await expect(page.getByRole('heading', { name: 'About', exact: true })).toBeVisible()
  const bankIds = await page.evaluate(async () => {
    const { createQuestionBankWorkspaceService } = await import(/* @vite-ignore */ '/src/question-bank-workspaces.ts') as typeof import('../src/question-bank-workspaces')
    const { createQuestion } = await import(/* @vite-ignore */ '/src/exam.ts') as typeof import('../src/exam')
    const service = createQuestionBankWorkspaceService()
    const banks = []
    for (const name of ['Biology', 'Chemistry']) {
      const bank = await service.create()
      await service.commit(bank.id, { kind: 'rename', name })
      for (let index = 1; index <= 3; index++) {
        const question = createQuestion('open')
        question.doc = { type: 'doc', content: [{ type: 'paragraph', content: [{ type: 'text', text: `${name} question ${index}` }] }] }
        await service.commit(bank.id, { kind: 'create-question', question })
      }
      banks.push(bank.id)
    }
    return banks
  })
  await page.goto('/')
  await page.getByRole('button', { name: 'Generate exam', exact: true }).click()
  const builder = page.locator('.exam-builder')
  await builder.getByLabel('Exam name', { exact: true }).fill('Random science paper')
  await builder.getByLabel('Total questions').fill('3')
  await builder.getByRole('button', { name: 'Choose banks', exact: true }).click()
  await builder.getByLabel('Questions from Biology').fill('1')
  await builder.getByLabel('Questions from Chemistry').fill('1')
  await builder.getByRole('button', { name: 'Review exam', exact: true }).click()
  await expect(builder.getByRole('alert')).toContainText('must add up')
  await builder.getByLabel('Questions from Biology').fill('2')
  await builder.getByRole('button', { name: 'Review exam', exact: true }).click()
  await builder.getByRole('button', { name: 'Generate exam', exact: true }).click()
  await expect(page).toHaveURL(/\/editor\?exam=/)
  const questions = page.locator('.draft-document .exam-question')
  await expect(questions).toHaveCount(3)
  await expect(questions.filter({ hasText: 'Biology question' })).toHaveCount(2)
  await expect(questions.filter({ hasText: 'Chemistry question' })).toHaveCount(1)
  const before = await questions.evaluateAll((elements) => elements.map((element) => element.getAttribute('data-question-id')))
  await questions.first().click()
  const dice = questions.first().getByRole('button', { name: /Replace question .* randomly/ })
  await expect(dice).toBeVisible()
  await dice.click()
  await expect(page.getByRole('status').filter({ hasText: 'Replaced question' })).toBeVisible()
  const after = await questions.evaluateAll((elements) => elements.map((element) => element.getAttribute('data-question-id')))
  expect(after[0]).not.toBe(before[0])
  expect(after.slice(1)).toEqual(before.slice(1))
  expect(new Set(after).size).toBe(3)
  await expect(questions.filter({ hasText: 'Biology question' })).toHaveCount(2)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect.poll(() => questions.evaluateAll((elements) => elements.map((element) => element.getAttribute('data-question-id')))).toEqual(before)
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await expect.poll(() => questions.evaluateAll((elements) => elements.map((element) => element.getAttribute('data-question-id')))).toEqual(after)
  await page.reload()
  await expect(questions).toHaveCount(3)
  await expect.poll(() => questions.evaluateAll((elements) => elements.map((element) => element.getAttribute('data-question-id')))).toEqual(after)
  const counts = await page.evaluate(async (ids) => {
    const { createQuestionBankWorkspaceService } = await import(/* @vite-ignore */ '/src/question-bank-workspaces.ts') as typeof import('../src/question-bank-workspaces')
    const service = createQuestionBankWorkspaceService()
    return Promise.all(ids.map(async (id) => (await service.read(id))!.questions.length))
  }, bankIds)
  expect(counts).toEqual([3, 3])
})

